export type Key = keyof typeof de;
const dictionaries = { de, en };

export function language(): "de" | "en" {
  const chosen = app.config?.language ?? "auto";
  if (chosen === "de" || chosen === "en") return chosen;
  return navigator.language.toLowerCase().startsWith("de") ? "de" : "en";
}

/** Translate; `{name}` in the text is replaced from `vars`. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return dictionaries[language()][key].replace(/\{(\w+)\}/g, (all, name: string) =>
    name in vars ? String(vars[name]) : all,
  );
}

/** 1.5 -> "1,5" in German. */
export function num(value: number): string {
  return value.toLocaleString(language(), { maximumFractionDigits: 1 });
}
